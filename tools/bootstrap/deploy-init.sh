#!/bin/bash
# Draft deploy.sh from the systemd units bootstrap captured under etc/systemd/system/.
# Run in the contest repo root (task deploy:init [APP_LANG=go]). Prints what it found, writes deploy.sh (backs up the old one).
set -eu
L=${1:-${LANGS%% *}}; L=${L:-go}   # arg, else first word of LANGS (.env), else go
cd "$(dirname "$0")/../.."
[ -d etc/systemd/system ] || { echo "etc/systemd/system/ not found — run after task hosts:setup + git pull"; exit 1; }
unit=$(ls etc/systemd/system/*-"$L".service 2>/dev/null | head -1 || true)
[ -n "$unit" ] || unit=$(grep -ls "WorkingDirectory=.*/webapp/$L" etc/systemd/system/*.service | head -1 || true)
[ -n "$unit" ] || { echo "no unit for language '$L' in etc/systemd/system/: $(ls etc/systemd/system)"; exit 1; }
name=$(basename "$unit")
wd=$(grep -m1 '^WorkingDirectory=' "$unit" | cut -d= -f2-)
ex=$(grep -m1 '^ExecStart=' "$unit" | cut -d= -f2-)
envf=$(grep -m1 '^EnvironmentFile=' "$unit" | cut -d= -f2- || true)
rel=${wd#/home/isucon/}; rel=${rel#/home/isucon}
bin=$(basename "${ex%% *}")
case "$L" in
  go)   build="( cd $rel && CGO_ENABLED=0 go build -o $bin -ldflags '-s -w' . )" ;;
  rust) build="( cd $rel && cargo build --release )" ;;
  node) build="( cd $rel && npm ci --omit=dev && npm run build 2>/dev/null || true )" ;;
  *)    build="# $L: no build step (interpreted)" ;;
esac
others=$(ls etc/systemd/system/ | grep -v "^$name$" | grep -vi "$L" | tr '\n' ' ')
# the other language implementations of the same app (<prefix>-<lang>.service): disabled in deploy.sh so only $name owns
# the app port (they Require the DB, so a DB restart or a crash-loop lets them grab :8080). Helpers such as
# <prefix>-matcher / -payment_mock are not languages and are left alone.
prefix=${name%-"$L".service}; langunits=""
if [ "$prefix" != "$name" ]; then
  for f in etc/systemd/system/"$prefix"-*.service; do
    [ -f "$f" ] || continue; u=$(basename "$f"); x=${u#"$prefix"-}; x=${x%.service}
    [ "$u" = "$name" ] && continue
    case "$x" in go|golang|node|nodejs|js|ts|typescript|perl|php|python|ruby|rust|java|kotlin|scala|crystal|elixir|csharp|dotnet) langunits="$langunits $u" ;; esac
  done
fi
langunits=${langunits# }
if [ -n "$langunits" ]; then disable_others="
# ---- 2c. only $name may own the app port: the AMI's other language units Require the DB too, so a DB restart or
# a crash-loop lets one of them take :8080 while $name restarts (a Go app that ignores ListenAndServe's error then exits
# silently). disable persists across reboots.
for u in $langunits; do
  sudo systemctl disable --now \"\$u\" 2>/dev/null || true
done
"; else disable_others=""; fi
cfg=""
site=$(ls etc/nginx/sites-enabled 2>/dev/null | head -1); nsites=$(ls etc/nginx/sites-enabled 2>/dev/null | wc -l | tr -d ' ')
# sites-enabled/<x> is usually a symlink (absolute, to /etc/nginx/sites-available/<x>): etc_install on it would copy
# nothing from the repo. Install the real file from sites-available and (re)point the link instead.
site_install() { # $1 = file name under sites-enabled
  if [ -L "etc/nginx/sites-enabled/$1" ] || { [ ! -e "etc/nginx/sites-enabled/$1" ] && [ -f "etc/nginx/sites-available/$1" ]; }; then
    [ -f "etc/nginx/sites-available/$1" ] || echo "  NOTE: etc/nginx/sites-enabled/$1 is a symlink but etc/nginx/sites-available/$1 is not in the repo - copy it there" >&2
    echo "etc_install etc/nginx/sites-available/$1 && sudo ln -sf /etc/nginx/sites-available/$1 /etc/nginx/sites-enabled/$1"
  else
    echo "etc_install etc/nginx/sites-enabled/$1"
  fi
}
if [ -d etc/nginx ] && [ "$nsites" = 1 ]; then cfg="$cfg
etc_install etc/nginx/nginx.conf && $(site_install "$site") && sudo nginx -t && sudo systemctl reload nginx"
elif [ -d etc/nginx ]; then
  for x in $(ls etc/nginx/sites-enabled 2>/dev/null); do cfg="$cfg
# etc_install etc/nginx/nginx.conf && $(site_install "$x") && sudo nginx -t && sudo systemctl reload nginx"; done
  if [ "$nsites" = 0 ]; then cfg="$cfg
# etc_install etc/nginx/nginx.conf && sudo nginx -t && sudo systemctl reload nginx"; fi
fi
[ -d etc/mysql ] && cfg="$cfg
# etc_install etc/mysql/mysql.conf.d/zz-isucon.cnf && sudo systemctl restart mysql     # restarting mysql also restarts $name (Requires=)"
[ -d etc/sysctl.d ] && cfg="$cfg
# etc_install etc/sysctl.d/99-isucon.conf && sudo sysctl --system >/dev/null"
[ -f deploy.sh ] && cp deploy.sh /tmp/deploy.sh.bak
cat > deploy.sh <<EOF
#!/bin/bash
# Runs ON EACH HOST as isucon after \`task deploy BRANCH=...\` (git fetch + reset --hard origin/<branch>).
# Generated by tools/bootstrap/deploy-init.sh from etc/systemd/system/$name — edit freely.
set -eu
cd "\$(dirname "\$0")"
export PATH=\$HOME/local/go/bin:\$HOME/local/golang/bin:\$HOME/go/bin:/usr/local/go/bin:\$HOME/.cargo/bin:\$PATH
for d in \$HOME/local/*/bin; do [ -d "\$d" ] && PATH=\$d:\$PATH; done   # the AMI puts toolchains under ~/local/<name>/bin
CONFIGURED=1
HOST=\$(hostname)
echo "== deploy on \$HOST: \$(git rev-parse --abbrev-ref HEAD)@\$(git rev-parse --short HEAD)"

# etc_install <repo path under etc/> : copy to /<path> keeping the original mode/owner recorded in etc/MODES.txt
# (never plain-copy config files: a 640 root file breaks tools the app user runs, e.g. pdnsutil)
etc_install() {
  local src="\$1" dst="/\$1" m
  m=\$(grep " \$dst\$" etc/MODES.txt 2>/dev/null | head -1)
  sudo install -D -m "\${m%% *}" -o "\$(echo "\$m" | cut -d' ' -f2)" -g "\$(echo "\$m" | cut -d' ' -f3)" "\$src" "\$dst" 2>/dev/null \\
    || sudo install -D -m 644 -o root -g root "\$src" "\$dst"
}
# tcp_ok <host> <port> : true when something listens there (checked before restarting the app so a dead DB fails loudly)
tcp_ok() { timeout 3 bash -c "</dev/tcp/\$1/\$2" 2>/dev/null; }

# ---- 0. DB host (fill when the DB moves to svc3; empty = single host). Set by parallel-setup A. ----
DB_HOST=""                # hostname of the DB host, e.g. ip-172-31-0-233
DB_PRIVATE_IP=""          # what app hosts dial, e.g. 172.31.0.233
if [ -n "\$DB_HOST" ] && [ "\$HOST" = "\$DB_HOST" ]; then
  # remote access: bind-address + grants (the AMI only has isucon@localhost; other hosts get Error 1130 without this)
  [ -f etc/mysql/mysql.conf.d/zz-remote.cnf ] && ! cmp -s etc/mysql/mysql.conf.d/zz-remote.cnf /etc/mysql/mysql.conf.d/zz-remote.cnf && { etc_install etc/mysql/mysql.conf.d/zz-remote.cnf; sudo systemctl restart mysql; }
  [ -f webapp/sql/zz-grant-remote.sql ] && sudo mysql < webapp/sql/zz-grant-remote.sql
  # performance defaults (flush_log_at_trx_commit=2, no binlog, max_connections): see the file's comments
  [ -f etc/mysql/mysql.conf.d/zz-perf.cnf ] && ! cmp -s etc/mysql/mysql.conf.d/zz-perf.cnf /etc/mysql/mysql.conf.d/zz-perf.cnf && { etc_install etc/mysql/mysql.conf.d/zz-perf.cnf; sudo systemctl restart mysql; }
fi
if [ -n "\$DB_PRIVATE_IP" ] && [ "\$HOST" != "\$DB_HOST" ]; then
  tcp_ok "\$DB_PRIVATE_IP" 3306 || { echo "!! DB \$DB_PRIVATE_IP:3306 unreachable from \$HOST (deploy the DB host first: task deploy does; else SG / bind-address)"; exit 1; }
fi
# per-host DB settings are NOT written into env.sh (some contests regenerate it at boot): keep them in env.db.sh and
# load it as a second EnvironmentFile via a systemd drop-in (etc/systemd/system/<unit>.d/db.conf); init.sh must source it too.

# ---- 1. build  (unit: $name, WorkingDirectory=$wd, ExecStart=$ex) ----
$build

# ---- 2. configs kept in the repo (etc/ mirrors /etc). Uncomment the lines for files you changed. ----$cfg
# per-host settings (DB host etc.) live in ${envf:-env.sh}: keep a copy per host in the repo and pick it here
# [ -f "env.\$HOST.sh" ] && cp "env.\$HOST.sh" ${envf:-env.sh}

# ---- 2a. reboot safety: keep restarting the app until the DB (possibly on another host) is up ----
# systemd's default start limit (5 starts / 10 s) turns "DB not ready yet" into a permanently failed unit after a reboot.
if [ -f etc/systemd/system/$name.d/restart.conf ]; then
  etc_install etc/systemd/system/$name.d/restart.conf && sudo systemctl daemon-reload
fi

# ---- 2b. indexes: webapp/sql/indexes/*.sql applied idempotently (index groups of parallel-fix only add files there) ----
[ -x webapp/sql/indexes/apply.sh ] && bash webapp/sql/indexes/apply.sh
$disable_others
# ---- 3. restart ----
sudo systemctl restart $name
sleep 1; systemctl is-active $name >/dev/null && echo "== $name active on \$HOST" || { echo "!! $name failed on \$HOST"; sudo journalctl -u $name -n 30 --no-pager; exit 1; }
EOF
chmod +x deploy.sh
mkdir -p "etc/systemd/system/$name.d"
[ -f "etc/systemd/system/$name.d/restart.conf" ] || cat > "etc/systemd/system/$name.d/restart.conf" <<EOR
# installed by deploy.sh: survive a DB that comes up later than the app after a reboot (cross-host DB, slow MySQL recovery)
[Unit]
StartLimitIntervalSec=0
After=network-online.target
[Service]
Restart=always
RestartSec=3
LimitNOFILE=65536
EOR
grep -q "etc/systemd/system/$name.d/restart.conf" etc/MODES.txt 2>/dev/null || echo "644 root root /etc/systemd/system/$name.d/restart.conf" >> etc/MODES.txt
mkdir -p etc/mysql/mysql.conf.d && [ -f etc/mysql/mysql.conf.d/zz-perf.cnf ] || cp "$(dirname "$0")/etc/mysql-zz-perf.cnf" etc/mysql/mysql.conf.d/zz-perf.cnf
grep -q "zz-perf.cnf" etc/MODES.txt 2>/dev/null || echo "644 root root /etc/mysql/mysql.conf.d/zz-perf.cnf" >> etc/MODES.txt
mkdir -p webapp/sql/indexes && cp -n "$(dirname "$0")/indexes-apply.sh" webapp/sql/indexes/apply.sh 2>/dev/null; chmod +x webapp/sql/indexes/apply.sh
grep -q 'indexes/apply.sh' webapp/sql/init.sh 2>/dev/null || echo "  NOTE: add 'bash \$(dirname \$0)/indexes/apply.sh' at the end of webapp/sql/init.sh so /initialize re-applies the indexes"
echo "deploy.sh written:"
echo "  unit      $name"
echo "  dir       $rel"
echo "  binary    $bin"
echo "  build     $build"
echo "  env file  ${envf:-?}"
[ -n "$others" ] && echo "  other units on the host: $others"
[ -n "$langunits" ] && echo "  disabled by deploy.sh (other languages): $langunits"
echo "review it (git diff deploy.sh), commit, then: task deploy"

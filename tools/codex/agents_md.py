#!/usr/bin/env python3
"""task agents:md — write AGENTS.md (what Codex CLI reads at the repo root) from CLAUDE.md.

AGENTS.md = a generated-file note + CLAUDE.md with each `@path` import line handled for Codex (Codex does not expand
Claude Code's @imports): inlined when the whole file stays under BUDGET bytes, else replaced by a "Read first" line
(Codex reads AGENTS.md up to project_doc_max_bytes, 32 KiB by default per the Codex docs — 未確認 offline; CLAUDE.md +
IMPLEMENTATION-NOTES.md are ~26 KB, so they do not both fit with the Codex section) + tools/codex/AGENTS.codex.md with
{{SKILLS}} replaced by the skill table built from .claude/skills/<name> → <target>/SKILL.md (name, path, description).

  python3 tools/codex/agents_md.py           write AGENTS.md
  python3 tools/codex/agents_md.py --check   exit 1 (and say why) when AGENTS.md differs from what would be written
ROOT=<dir> overrides the repo root (tests).
"""
import os
import re
import sys

BUDGET = 28000  # bytes of AGENTS.md below Codex's default 32 KiB project-doc limit, with room to spare
IMPORT_RE = re.compile(r"^@(\S+)\s*$")
HEADER = ("<!-- GENERATED by `task agents:md` from CLAUDE.md + tools/codex/AGENTS.codex.md. Do not edit this file: "
          "edit those and run `task agents:md` (the tests fail while it is stale). -->\n"
          "# AGENTS.md — for Codex CLI (same rules as CLAUDE.md)\n\n"
          "Codex: this is CLAUDE.md for you. Where it says Claude / Claude Code, read Codex; the differences are in the "
          "last section 「Codex で動くとき（Claude Code との違い）」. Read that section first.\n\n")


def root():
    return os.environ.get("ROOT") or os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def description(skill_md):
    """The frontmatter description, cut at the first 。 (one line)."""
    try:
        text = read(skill_md)
    except OSError:
        return ""
    m = re.search(r"^description:\s*(.+)$", text, re.M)
    d = (m.group(1).strip().strip("\"'") if m else "")
    if "。" in d:
        d = d.split("。")[0] + "。"
    return d.replace("|", "/")


def skills(r):
    d = os.path.join(r, ".claude", "skills")
    rows = []
    for name in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        p = os.path.join(d, name)
        target = os.path.realpath(p)
        md = os.path.join(target, "SKILL.md")
        if not os.path.isfile(md):
            continue
        rel = os.path.relpath(md, os.path.realpath(r))
        rows.append(f"| `{name}` | `{rel}` | {description(md)} |")
    if not rows:
        return "（`.claude/skills/` に skill が無い）"
    return "| skill | 読むファイル | 何をするか |\n|---|---|---|\n" + "\n".join(rows)


def build(r=None):
    r = r or root()
    claude = read(os.path.join(r, "CLAUDE.md"))
    section = read(os.path.join(r, "tools", "codex", "AGENTS.codex.md")).replace("{{SKILLS}}", skills(r))
    imports = [m.group(1) for m in (IMPORT_RE.match(x) for x in claude.splitlines()) if m]
    inline_size = len(HEADER.encode()) + len(claude.encode()) + len(section.encode()) + sum(
        len(read(os.path.join(r, p)).encode()) for p in imports if os.path.isfile(os.path.join(r, p)))
    inline = inline_size <= BUDGET
    out = []
    for line in claude.splitlines():
        m = IMPORT_RE.match(line)
        if not m:
            out.append(line)
            continue
        p = m.group(1)
        if inline and os.path.isfile(os.path.join(r, p)):
            out += [f"<!-- inlined from {p} -->", read(os.path.join(r, p)).rstrip("\n"), f"<!-- end of {p} -->"]
        else:
            out.append(f"**Read first: `{p}`** — Claude Code imports it into every session automatically; Codex does not "
                       f"expand `@` imports, so open and read that file before you change anything.")
    return HEADER + "\n".join(out).rstrip("\n") + "\n\n" + section.rstrip("\n") + "\n"


def main(argv):
    r = root()
    want = build(r)
    path = os.path.join(r, "AGENTS.md")
    try:
        have = read(path)
    except OSError:
        have = None
    if "--check" in argv:
        if have != want:
            print("!! AGENTS.md is stale (or missing): run `task agents:md` and commit it", file=sys.stderr)
            return 1
        print("AGENTS.md is up to date")
        return 0
    if have != want:
        with open(path, "w", encoding="utf-8") as f:
            f.write(want)
        print(f"wrote {path} ({len(want.encode())} bytes)")
    else:
        print("AGENTS.md is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
